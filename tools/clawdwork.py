#!/usr/bin/env python3
"""Generate src/ui/clawd_work.h — Clawd's "working" frames (P-2026-11-26.13).

Source: design/panel/tokens/panel_tokens.json → themeXP.clawdWork.frames, each
a list of 13 rows × 23 cells: '.' body (xpBody), 'C' Clawd, 'K' eye (black),
'L' laptop (xpLaptop). Packed 2 bits per cell, 4 cells per byte, MSB first:
0 = body, 1 = Clawd, 2 = eye, 3 = laptop. Frame order = the token's key order
(intro frames first, then the typing loop); clawd_work_core.h indexes them.

    python tools/clawdwork.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOK = ROOT / "design/panel/tokens/panel_tokens.json"
OUT = ROOT / "src/ui/clawd_work.h"
CODE = {".": 0, "C": 1, "K": 2, "L": 3}


def main():
    cw = json.loads(TOK.read_text(encoding="utf-8"))["themeXP"]["clawdWork"]
    frames = cw["frames"]
    keys = list(frames)
    rows0 = frames[keys[0]]
    nrows, ncols = len(rows0), len(rows0[0])
    bpr = (ncols + 3) // 4
    out = []
    for k in keys:
        rows = frames[k]
        assert len(rows) == nrows and all(len(r) == ncols for r in rows), k
        fr = []
        for r in rows:
            b = [0] * bpr
            for i, ch in enumerate(r):
                b[i // 4] |= CODE[ch] << (6 - 2 * (i % 4))
            fr.append("{" + ", ".join(f"0x{v:02X}" for v in b) + "}")
        out.append(f"    {{ // GIF frame {k}\n        " + ",\n        ".join(fr) + "\n    }")
    body = ",\n".join(out)
    text = f"""// GENERATED by tools/clawdwork.py from design/panel/tokens/panel_tokens.json
// (themeXP.clawdWork.frames, P-2026-11-26.13) — do not edit by hand.
// Clawd at work, copied from the Clawd GIF: {len(keys)} frames, {nrows} rows × {ncols} cells,
// 2 bits / cell (0 body, 1 Clawd, 2 eye, 3 laptop), 4 cells / byte, MSB first.
// Frame order: GIF frames {", ".join(keys)}.
#pragma once
#include <stdint.h>
#ifndef PROGMEM
#define PROGMEM
#endif

namespace ClawdWorkBits {{
constexpr int kFrames = {len(keys)};
constexpr int kRows = {nrows};
constexpr int kCols = {ncols};
constexpr int kBytesPerRow = {bpr};

static const uint8_t kFrame[kFrames][kRows][kBytesPerRow] PROGMEM = {{
{body}
}};
}}  // namespace ClawdWorkBits
"""
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {len(keys)} frames, {len(keys) * nrows * bpr} bytes")


if __name__ == "__main__":
    main()
