#!/usr/bin/env python3
"""Fallback desktop wallpaper (P-2026-11-26.12) → src/ui/desk_wallpaper.h.

Rasterises the wallpaper rectangles of design/panel/source/XP-Desktop.dc.html
(every absolutely positioned <div> before the first icon <svg>) into a
240×214 image of the 24 `xpDesk_*` colours (token themeXP.color), then
run-length encodes it row by row: byte pairs (palette index, run length),
each row's runs summing to 240. ~2 KB of flash; the firmware draws it with
one drawFastHLine per run and tools/screens.py reads the same header.

    python tools/deskwall.py            # regenerate the header
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "design", "panel", "source", "XP-Desktop.dc.html")
TOK = os.path.join(ROOT, "design", "panel", "tokens", "panel_tokens.json")
OUT = os.path.join(ROOT, "src", "ui", "desk_wallpaper.h")
W, H = 240, 214

RECT = re.compile(r'<div style="position: absolute; left: (-?\d+)px; top: (-?\d+)px; '
                  r'width: (\d+)px; height: (\d+)px; background: (#[0-9A-Fa-f]{6});"')


def main():
    html = open(SRC, encoding="utf-8").read()
    color = json.load(open(TOK, encoding="utf-8"))["themeXP"]["color"]
    pal = sorted(((k, v["value"].upper(), v["rgb565"]) for k, v in color.items()
                  if k.startswith("xpDesk_")), key=lambda p: p[0])
    index = {hexv: i for i, (_, hexv, _) in enumerate(pal)}

    body = html[html.index('<div style="position: relative'):]
    body = body[:body.index("<svg")]
    img = [[None] * W for _ in range(H)]
    for m in RECT.finditer(body):
        x, y, w, h = map(int, m.groups()[:4])
        c = index[m.group(5).upper()]
        for yy in range(max(0, y), min(H, y + h)):
            for xx in range(max(0, x), min(W, x + w)):
                img[yy][xx] = c
    holes = sum(v is None for row in img for v in row)
    if holes:
        sys.exit(f"{holes} pixels not covered by the wallpaper rectangles")

    runs = []
    for row in img:
        x = 0
        while x < W:
            k = 1
            while x + k < W and row[x + k] == row[x]:
                k += 1
            runs.append((row[x], k))
            x += k

    lines = [
        "#pragma once",
        "// GENERATED by tools/deskwall.py from design/panel/source/XP-Desktop.dc.html",
        "// (P-2026-11-26.12) — do not edit. Fallback desktop wallpaper 240×214:",
        "// kDeskRuns = (palette index, run length) byte pairs, row after row, each",
        "// row's runs summing to kDeskW. Palette = token themeXP.color xpDesk_*.",
        "#include <stdint.h>",
        "#ifdef ARDUINO",
        "#include <pgmspace.h>",
        "#else",
        "#define PROGMEM",
        "#endif",
        "",
        "namespace Desk {",
        f"constexpr int kDeskW = {W}, kDeskH = {H};",
        f"constexpr int kDeskPalN = {len(pal)};",
        "const uint16_t kDeskPal[kDeskPalN] PROGMEM = {",
    ]
    for name, hexv, rgb in pal:
        lines.append(f"    {rgb},  // {hexv} {name}")
    lines.append("};")
    lines.append(f"constexpr int kDeskRunCount = {len(runs)};")
    lines.append("const uint8_t kDeskRuns[kDeskRunCount * 2] PROGMEM = {")
    flat = [v for r in runs for v in r]
    for i in range(0, len(flat), 24):
        lines.append("    " + ", ".join(str(v) for v in flat[i:i + 24]) + ",")
    lines.append("};")
    lines.append("}  // namespace Desk")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"{OUT}: {len(runs)} runs, {len(flat)} B + palette {len(pal)}")


if __name__ == "__main__":
    main()
