#!/usr/bin/env python3
"""Generate the XP colour icons drawn at real pixels from the panel design sources.

- src/ui/desk_icons.h  — desktop icons Codex (Command Prompt), Ảnh (My Pictures), Thùng rác (Recycle Bin), 32×23
  (P-2026-11-26.19, source/XP-Desk-Icons.dc.html).
- src/ui/warn_icon.h  — XP's warning triangle 24×21 (P-2026-11-26.23, source/XP-Weather-Error.dc.html).
- src/ui/start_icons.h — the Start menu's icons (P-2026-11-26.20, source/XP-Start-All.dc.html): user picture Clawd,
  pinned Clawd ×2, 16-px program / place icons, the All Programs arrow, Restart / Turn off buttons.

Each <svg> is found by its position in the source; each <path fill="#RRGGBB"> is one colour, its `M x y h w v1 h-w z`
pieces are horizontal runs. Cells with no path are transparent. Output per icon: a palette (RGB565), runs
{x, y, w, colour index}, and its size, in flash.

    python tools/deskicons.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "design/panel/source"

SETS = [
    ("XP-Desk-Icons.dc.html", "src/ui/desk_icons.h", "DeskIcons", "P-2026-11-26.19", [
        ("Codex", 24, 56), ("Photo", 24, 104), ("Trash", 24, 152),
    ]),
    ("XP-Start-All.dc.html", "src/ui/start_icons.h", "StartIcons", "P-2026-11-26.20", [
        ("UserClawd", 9, 11), ("PinClawd", 3, 39), ("Photo", 6, 102), ("Weather", 6, 121), ("Clock", 6, 141),
        ("AllArrow", 138, 171), ("Desktop", 156, 40), ("Stats", 156, 61), ("Settings", 156, 90),
        ("AddRemove", 156, 111), ("Device", 156, 132), ("Restart", 8, 194), ("Power", 165, 194),
        ("SmallClawd", 154, 69), ("SmallCodex", 154, 88),
    ]),
    ("XP-Weather-Error.dc.html", "src/ui/warn_icon.h", "WarnIcon", "P-2026-11-26.23", [
        ("Warn", 14, 52),
    ]),
    # P-2026-11-28.28–.32: Task Manager, Calculator, Explorer (My Computer, drive, folder, Recycle Bin empty / full).
    # A 4th field names another source file of the set.
    ("XP-TaskMgr-Apps.dc.html", "src/ui/xp_icons.h", "XpIcons", "P-2026-11-28.28–.32", [
        ("TaskMgr", 4, 3),
        ("Calc", 4, 3, "XP-Calc.dc.html"),
        ("Computer", 4, 3, "XP-Explorer-Computer.dc.html"),
        ("Drive", 10, 50, "XP-Explorer-Computer.dc.html"),
        ("Folder", 10, 160, "XP-Explorer-Computer.dc.html"),
        ("TrashSmall", 4, 3, "XP-Explorer-TrashEmpty.dc.html"),
        ("TrashSmallFull", 4, 3, "XP-Explorer-Trash.dc.html"),
        ("TrashFull", 24, 152, "XP-Desk-TrashFull.dc.html"),
    ]),
]


def rgb565(h):
    r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3


def icon(html, left, top):
    m = re.search(rf'<svg[^>]*left: {left}px; top: {top}px;[^>]*width="(\d+)" height="(\d+)" '
                  rf'viewBox="0 0 (\d+) (\d+)"[^>]*>(.*?)</svg>', html, re.S)
    assert m, f"icon at ({left}, {top}) not found"
    w, h, vw, vh, body = m.groups()
    assert (w, h) == (vw, vh), f"icon at ({left}, {top}) is scaled"
    pal, runs = [], []
    for fill, d in re.findall(r'<path fill="#([0-9A-Fa-f]{6})" d="([^"]*)"', body):
        idx = len(pal)
        pal.append((fill.upper(), rgb565(fill)))
        for x, y, rw in re.findall(r"M(\d+) (\d+)h(\d+)v1h-\d+z", d):
            runs.append((int(x), int(y), int(rw), idx))
    runs.sort(key=lambda r: (r[1], r[0]))
    return int(w), int(h), pal, runs


def emit(src, out, ns, code, icons):
    html = (SRC / src).read_text(encoding="utf-8")
    parts = []
    for name, left, top, *other in icons:
        w, h, pal, runs = icon((SRC / other[0]).read_text(encoding="utf-8") if other else html, left, top)
        assert len(pal) < 256 and all(x + rw <= w and y < h for x, y, rw, _ in runs), name
        pal_s = ",\n    ".join(f"0x{c:04X}  /* #{hx} */" for hx, c in pal)
        run_s = ",\n    ".join(", ".join(f"{{{x}, {y}, {rw}, {i}}}" for x, y, rw, i in runs[k:k + 6])
                               for k in range(0, len(runs), 6))
        parts.append(f"""// {name}: {w}×{h}, {len(pal)} colours, {len(runs)} runs
static const uint16_t k{name}Pal[] PROGMEM = {{
    {pal_s}
}};
static const Run k{name}Runs[] PROGMEM = {{
    {run_s}
}};
constexpr int k{name}RunCount = {len(runs)}, k{name}W = {w}, k{name}H = {h};
""")
    text = f"""// GENERATED by tools/deskicons.py from design/panel/source/{src} ({code})
// — do not edit by hand. XP colour icons at real pixels: horizontal runs of one palette colour; cells with no run
// are transparent (what is under them shows).
#pragma once
#include <stdint.h>
#ifndef PROGMEM
#define PROGMEM
#endif

namespace {ns} {{
struct Run {{ uint8_t x, y, w, c; }};

{chr(10).join(parts)}}}  // namespace {ns}
"""
    (ROOT / out).write_text(text, encoding="utf-8", newline="\n")
    print(f"{out}: {', '.join(i[0] for i in icons)}")


DART_OUT = ROOT / "app/lib/ui/control/widgets/device_mirror/desk_icons_xp.dart"


def emit_dart():
    """The desktop icons for the app's mirror (same pixels as the device)."""
    html = (SRC / "XP-Desk-Icons.dc.html").read_text(encoding="utf-8")
    parts = []
    for name, left, top in SETS[0][4]:
        w, h, pal, runs = icon(html, left, top)
        pal_s = ", ".join(f"Color(0xFF{hx})" for hx, _ in pal)
        run_s = ", ".join(f"({x}, {y}, {rw}, {i})" for x, y, rw, i in runs)
        parts.append(f"  static const {name[0].lower() + name[1:]} = XpRunIcon([{pal_s}], [{run_s}]);")
    text = f"""// GENERATED by tools/deskicons.py from design/panel/source/XP-Desk-Icons.dc.html (P-2026-11-26.19)
// — do not edit by hand. The device's XP desktop icons 32×23 (src/ui/desk_icons.h) for the mirror.
// ignore_for_file: lines_longer_than_80_chars
import 'dart:ui';

/// An icon of horizontal runs (x, y, width, palette index); cells with no run are transparent.
class XpRunIcon {{
  const XpRunIcon(this.palette, this.runs);

  final List<Color> palette;
  final List<(int, int, int, int)> runs;
}}

/// Codex = Command Prompt, Ảnh = My Pictures, Thùng rác = Recycle Bin.
abstract final class DeskIconsXp {{
{chr(10).join(parts)}
}}
"""
    DART_OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{DART_OUT.relative_to(ROOT)}: desk icons")


if __name__ == "__main__":
    for s in SETS:
        emit(*s)
    emit_dart()
