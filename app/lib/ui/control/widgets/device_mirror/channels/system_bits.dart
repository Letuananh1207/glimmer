  /// `XP::drawBits`: [bytes] of a [w] × [h] bitmap at (x, y) in [color], runs of lit pixels as rects.
  static void draw(XpCanvas c, List<int> bytes, int w, int h, num x, num y, Color color) {
    final nb = (w + 7) >> 3;
    bool lit(int r, int i) => bytes[r * nb + (i >> 3)] & (0x80 >> (i & 7)) != 0;
    for (var r = 0; r < h; r++) {
      var i = 0;
      while (i < w) {
        if (!lit(r, i)) {
          i++;
          continue;
        }
        var run = 1;
        while (i + run < w && lit(r, i + run)) {
          run++;
        }
        c.fill(x + i, y + r, run, 1, color);
        i += run;
      }
    }
  }
