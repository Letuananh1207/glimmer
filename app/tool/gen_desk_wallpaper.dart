// Fallback desktop wallpaper of the device (P-2026-11-26.12) → the app's DeviceMirror.
//
// Reads the firmware's generated run table `../src/ui/desk_wallpaper.h` (tools/deskwall.py) and writes
// `lib/ui/control/widgets/device_mirror/channels/desk_wallpaper.dart`: the 24-colour palette as `XpColors.desk*`
// (same order as the header: sorted by token name) and the runs as one hex string, 4 hex digits per run (palette
// index, run length), row after row, each row's runs summing to 240.
//
//   dart tool/gen_desk_wallpaper.dart        (from app/; re-run when the firmware header changes)
import 'dart:io';

const _src = '../src/ui/desk_wallpaper.h';
const _out = 'lib/ui/control/widgets/device_mirror/channels/desk_wallpaper.dart';

void main() {
  final h = File(_src).readAsStringSync();
  final palSrc = h.substring(h.indexOf('kDeskPal[kDeskPalN]'), h.indexOf('};'));
  final pal = RegExp(r'// #([0-9A-F]{6})').allMatches(palSrc).map((m) => m[1]!).toList();
  var runs = h.substring(h.indexOf('kDeskRuns[kDeskRunCount * 2]'));
  runs = runs.substring(runs.indexOf('{') + 1, runs.indexOf('};'));
  final v = RegExp(r'\d+').allMatches(runs).map((m) => int.parse(m[0]!)).toList();
  if (v.length.isOdd) throw StateError('odd run table');
  final hex = StringBuffer();
  for (var i = 0; i < v.length; i += 2) {
    hex
      ..write(v[i].toRadixString(16).padLeft(2, '0'))
      ..write(v[i + 1].toRadixString(16).padLeft(2, '0'));
  }
  final s = hex.toString();
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_desk_wallpaper.dart from ../src/ui/desk_wallpaper.h — do not edit.')
    ..writeln('// Fallback desktop wallpaper 240 × 214 of the device (P-2026-11-26.12, tools/deskwall.py).')
    ..writeln("import 'dart:ui';")
    ..writeln()
    ..writeln("import '../../../../core/themes/xp_colors.dart';")
    ..writeln()
    ..writeln('/// The fallback wallpaper: [palette] and the run table [runs].')
    ..writeln('abstract final class DeskWallpaper {')
    ..writeln('  static const width = 240, height = 214;')
    ..writeln()
    ..writeln('  /// `xpDesk_*` colours, in the header\'s order (index of a run).')
    ..writeln('  static const palette = <Color>[');
  for (final p in pal) {
    out.writeln('    XpColors.desk$p,');
  }
  out
    ..writeln('  ];')
    ..writeln()
    ..writeln('  /// ${v.length ~/ 2} runs, 4 hex digits each: palette index, run length.')
    ..writeln('  static const runs =');
  for (var i = 0; i < s.length; i += 96) {
    final end = i + 96 > s.length ? s.length : i + 96;
    out.writeln("      '${s.substring(i, end)}'${end == s.length ? ';' : ''}");
  }
  out.writeln('}');
  File(_out)
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  stdout.writeln('$_out: ${v.length ~/ 2} runs, ${pal.length} colours');
}
